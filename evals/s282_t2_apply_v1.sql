-- Captura del before-image + UPDATE fill-only en una sola sentencia atómica.
CREATE TEMP TABLE t2_apply_audit (
  document_id uuid, source_file text,
  old_doc_type text, new_doc_type text,
  old_language text, new_language text
) ON COMMIT DROP;

WITH before AS (
  SELECT d.id, d.doc_type AS old_doc_type, d.language AS old_language
  FROM documents d JOIN t2_staging s ON d.id = s.document_id
  WHERE d.doc_type IS NULL OR d.language IS NULL
),
upd AS (
  UPDATE documents d SET
    doc_type = COALESCE(d.doc_type, s.doc_type),   -- fill-only; nunca overwrite
    language = COALESCE(d.language, s.language)     -- SOLO singleton; multi = NULL en staging
  FROM t2_staging s
  WHERE d.id = s.document_id
    AND (d.doc_type IS NULL OR d.language IS NULL)
  RETURNING d.id, s.source_file, d.doc_type AS new_doc_type, d.language AS new_language
)
INSERT INTO t2_apply_audit (document_id, source_file, old_doc_type, new_doc_type, old_language, new_language)
SELECT u.id, u.source_file, b.old_doc_type, u.new_doc_type, b.old_language, u.new_language
FROM upd u JOIN before b ON b.id = u.id;

-- Verificación post-apply (aborta la transacción si algo no cuadra).
DO $$ DECLARE n_upd int; n_dt int; n_lang int; n_overwrite int; BEGIN
  SELECT count(*) INTO n_upd  FROM t2_apply_audit;
  SELECT count(*) INTO n_dt   FROM t2_apply_audit WHERE old_doc_type IS NULL AND new_doc_type IS NOT NULL;
  SELECT count(*) INTO n_lang FROM t2_apply_audit WHERE old_language IS NULL AND new_language IS NOT NULL;
  SELECT count(*) INTO n_overwrite FROM t2_apply_audit
    WHERE (old_doc_type IS NOT NULL AND old_doc_type IS DISTINCT FROM new_doc_type)
       OR (old_language IS NOT NULL AND old_language IS DISTINCT FROM new_language);
  RAISE NOTICE 'T2-apply: updated=% doc_type_set=% language_set=% overwrites=%',
               n_upd, n_dt, n_lang, n_overwrite;
  IF n_upd       <> 533 THEN RAISE EXCEPTION 'updated % <> 533', n_upd; END IF;
  IF n_dt        <> 533 THEN RAISE EXCEPTION 'doc_type_set % <> 533', n_dt; END IF;
  IF n_lang      <> 301 THEN RAISE EXCEPTION 'language_set % <> 301', n_lang; END IF;
  IF n_overwrite <> 0 THEN RAISE EXCEPTION 'overwrite detectado (%): fill-only violado', n_overwrite; END IF;
END $$;

